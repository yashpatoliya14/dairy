  static String t(String text, {String? language}) {
    final controller = Get.isRegistered<AppLanguageController>()
        ? Get.find<AppLanguageController>()
        : null;
    final currentLang = language ?? controller?.language.value ?? 'en';
    if (currentLang == 'en') return text;
    final translated = _translations[currentLang]?[text];
    if (translated != null && translated.isNotEmpty) {
      return translated;
    }
    return text;
  }
